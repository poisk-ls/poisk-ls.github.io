#!/usr/bin/env node
/* Regenerates assets/js/offline-data.js from assets/data/*.json.
   Run it after editing any JSON in assets/data so the file:// copy stays in sync:
       node tools/build-offline-data.js
   (Only needed for offline/file:// use; a web server reads the .json files directly.) */
const fs = require('fs'), path = require('path');
const root = path.resolve(__dirname, '..');
const dir = path.join(root, 'assets', 'data');
const data = {};
fs.readdirSync(dir).filter(f => f.endsWith('.json')).sort().forEach(f => {
  data['assets/data/' + f] = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
});
const out = '/* GENERATED by tools/build-offline-data.js from assets/data/*.json - do not edit by hand.\n' +
  '   Used only on file:// (see file-compat.js). */\nwindow.__OFFLINE_DATA = ' + JSON.stringify(data) + ';\n';
fs.writeFileSync(path.join(root, 'assets', 'js', 'offline-data.js'), out);
console.log('offline-data.js written (' + Object.keys(data).length + ' files, ' + out.length + ' bytes)');
