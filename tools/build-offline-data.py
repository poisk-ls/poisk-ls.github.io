#!/usr/bin/env python3
"""Regenerates assets/js/offline-data.js from assets/data/*.json (same as the .js tool).
Run after editing any JSON in assets/data:   python tools/build-offline-data.py"""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
data = {f"assets/data/{p.name}": json.loads(p.read_text(encoding="utf-8"))
        for p in sorted((root / "assets" / "data").glob("*.json"))}
out = ("/* GENERATED by tools/build-offline-data.py from assets/data/*.json - do not edit by hand.\n"
       "   Used only on file:// (see file-compat.js). */\nwindow.__OFFLINE_DATA = "
       + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")
(root / "assets" / "js" / "offline-data.js").write_text(out, encoding="utf-8")
print(f"offline-data.js written ({len(data)} files, {len(out)} bytes)")
